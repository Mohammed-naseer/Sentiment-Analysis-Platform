import { genAI, isGeminiInitialized } from '../config/gemini';
import logger from '../utils/logger';

export interface ModelSentimentResult {
  sentiment: 'Positive' | 'Negative' | 'Neutral';
  confidence: number; // 0 - 100
  emotion: string;
  summary: string;
}

/**
 * Analyze Sentiment using Gemini API
 */
export const analyzeWithGemini = async (text: string): Promise<ModelSentimentResult> => {
  if (!isGeminiInitialized || !genAI) {
    logger.warn('[GeminiService] Gemini API not initialized. Using fallback mock.');
    return getMockResult(text, 'Gemini');
  }

  try {
    const model = genAI.getGenerativeModel({
      model: 'gemini-1.5-flash',
      systemInstruction: 'You are an AI sentiment analysis engine. Analyze the input text and return a JSON object with: sentiment (one of "Positive", "Negative", "Neutral"), confidence (an integer between 0 and 100 representing the certainty percentage), emotion (a single descriptive word for the primary emotion, e.g. Happy, Angry, Sad, Neutral, Frustrated, Excited, Grateful, Surprised), and summary (a concise 1-sentence explanation of why that sentiment/emotion was chosen). Do not return markdown. Return only raw JSON.',
      generationConfig: {
        responseMimeType: 'application/json',
      },
    });

    const response = await model.generateContent(`Analyze the sentiment of this text:\n\n"${text}"`);
    const responseText = response.response.text();

    if (!responseText) {
      throw new Error('Received empty response from Gemini API.');
    }

    const parsed = JSON.parse(responseText.trim());
    return {
      sentiment: sanitizeSentiment(parsed.sentiment),
      confidence: typeof parsed.confidence === 'number' ? parsed.confidence : 75,
      emotion: parsed.emotion || 'Neutral',
      summary: parsed.summary || 'Summary generated by Gemini.',
    };
  } catch (error: any) {
    logger.error('[GeminiService] Error calling Gemini API:', error.message);
    return getMockResult(text, 'Gemini');
  }
};

export const sanitizeSentiment = (val: string): 'Positive' | 'Negative' | 'Neutral' => {
  const norm = String(val).trim().toLowerCase();
  if (norm.includes('pos')) return 'Positive';
  if (norm.includes('neg')) return 'Negative';
  return 'Neutral';
};

export const getMockResult = (text: string, provider: string): ModelSentimentResult => {
  const lower = text.toLowerCase();
  let sentiment: 'Positive' | 'Negative' | 'Neutral' = 'Neutral';
  let emotion = 'Neutral';
  let confidence = 65 + Math.floor(Math.random() * 25);
  
  if (lower.includes('love') || lower.includes('great') || lower.includes('awesome') || lower.includes('excellent')) {
    sentiment = 'Positive';
    emotion = 'Happy';
  } else if (lower.includes('bad') || lower.includes('slow') || lower.includes('bug') || lower.includes('broken') || lower.includes('hate')) {
    sentiment = 'Negative';
    emotion = 'Frustrated';
  }

  return {
    sentiment,
    confidence,
    emotion,
    summary: `[Fallback] ${provider} analyzed the text and found ${sentiment.toLowerCase()} sentiment (simulated response).`
  };
};
