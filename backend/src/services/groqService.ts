import { groq, isGroqInitialized } from '../config/groq';
import { ModelSentimentResult, sanitizeSentiment } from './geminiService';
import { config } from '../config/env';
import logger from '../utils/logger';

/**
 * Analyze Sentiment & Granular Aspects using Groq API
 */
export const analyzeWithGroq = async (text: string, requestId?: string): Promise<ModelSentimentResult> => {
  const startTime = Date.now();
  const reqId = requestId || `req_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`;

  if (!isGroqInitialized || !groq) {
    logger.warn('[GroqService] Groq SDK not initialized.');
    return failGroqResult('SDK_NOT_INITIALIZED', 'Groq API key not configured', reqId, startTime);
  }

  try {
    const response = await groq.chat.completions.create({
      model: config.groqModel,
      messages: [
        {
          role: 'system',
          content:
            'You are an AI customer sentiment analysis engine. Analyze the input text and return a JSON object with: ' +
            'sentiment (one of "Positive", "Negative", "Neutral", "Mixed"), ' +
            'confidence (an integer between 0 and 100 representing certainty percentage), ' +
            'emotion (a single descriptive word for primary emotion, e.g. Frustrated, Happy, Satisfied, Concerned, Anger, Disappointment, Excited, Neutral), ' +
            'emotionConfidence (an integer between 0 and 100), ' +
            'summary (a concise 1-sentence explanation), ' +
            'and aspects (an array of objects each with { aspect: string, sentiment: "POSITIVE"|"NEGATIVE"|"NEUTRAL", confidence: float 0.0-1.0, evidence: string verbatim quote from text }). ' +
            'If positive and negative elements both exist substantially, use "Mixed". Do not return markdown. Return only raw JSON.'
        },
        {
          role: 'user',
          content: `Analyze the sentiment and aspects of this text:\n\n"${text.length > 8000 ? text.slice(0, 8000) : text}"`
        }
      ],
      response_format: { type: 'json_object' },
      temperature: 0.1,
    });

    const latencyMs = Date.now() - startTime;
    const responseText = response.choices[0]?.message?.content;
    if (!responseText) {
      throw new Error('Received empty response from Groq API.');
    }

    const parsed = JSON.parse(responseText.trim());
    const result: ModelSentimentResult = {
      sentiment: sanitizeSentiment(parsed.sentiment),
      confidence: typeof parsed.confidence === 'number' ? Math.min(100, Math.max(0, Math.round(parsed.confidence))) : 80,
      emotion: parsed.emotion || 'Neutral',
      emotionConfidence: typeof parsed.emotionConfidence === 'number' ? Math.min(100, Math.max(0, Math.round(parsed.emotionConfidence))) : 80,
      summary: parsed.summary || 'Summary generated by Groq.',
      aspects: Array.isArray(parsed.aspects) ? parsed.aspects.map((a: any) => ({
        aspect: String(a.aspect || 'General'),
        sentiment: (String(a.sentiment || 'NEUTRAL').toUpperCase() as any),
        confidence: typeof a.confidence === 'number' ? Math.min(1, Math.max(0, a.confidence)) : 0.8,
        evidence: String(a.evidence || ''),
      })) : [],
      status: 'success',
      latencyMs,
      model: config.groqModel,
    };

    logger.info('[GroqService] Structured Provider Log:', {
      provider: 'Groq',
      requestId: reqId,
      status: 'success',
      latency: `${latencyMs}ms`,
      model: config.groqModel,
      sentiment: result.sentiment,
      confidence: result.confidence,
      timestamp: new Date().toISOString(),
    });

    return result;
  } catch (error: any) {
    logger.error('[GroqService] Error calling Groq API:', error.message);
    return failGroqResult('PROVIDER_ERROR', error.message, reqId, startTime);
  }
};

function failGroqResult(errorCode: string, rawReason: string, requestId: string, startTime: number): ModelSentimentResult {
  const latencyMs = Date.now() - startTime;
  let safeReason = rawReason || 'Groq provider failed';
  if (safeReason.includes('API key') || safeReason.includes('auth')) {
    safeReason = 'Authentication credentials rejected by Groq';
  } else if (safeReason.includes('rate limit') || safeReason.includes('429')) {
    safeReason = 'Groq rate limit exceeded';
  }

  logger.warn('[GroqService] Structured Provider Failure Log:', {
    provider: 'Groq',
    requestId,
    status: 'failed',
    latency: `${latencyMs}ms`,
    errorCode,
    errorMessage: safeReason,
    model: config.groqModel,
    timestamp: new Date().toISOString(),
  });

  return {
    sentiment: 'Neutral',
    confidence: 0,
    emotion: 'Unknown',
    summary: `[Fallback] Groq failed: ${safeReason}`,
    status: 'failed',
    errorCode,
    errorMessage: safeReason,
    latencyMs,
    model: config.groqModel,
  };
}

