import { groq, isGroqInitialized } from '../config/groq';
import { ModelSentimentResult, sanitizeSentiment, getMockResult } from './geminiService';
import logger from '../utils/logger';

/**
 * Analyze Sentiment using Groq API
 */
export const analyzeWithGroq = async (text: string): Promise<ModelSentimentResult> => {
  if (!isGroqInitialized || !groq) {
    logger.warn('[GroqService] Groq SDK not initialized. Using fallback mock.');
    return getMockResult(text, 'Groq');
  }

  try {
    const response = await groq.chat.completions.create({
      model: 'llama-3.3-70b-versatile',
      messages: [
        {
          role: 'system',
          content: 'You are an AI sentiment analysis engine. Analyze the input text and return a JSON object with: sentiment (one of "Positive", "Negative", "Neutral"), confidence (an integer between 0 and 100 representing the certainty percentage), emotion (a single descriptive word for the primary emotion, e.g. Happy, Angry, Sad, Neutral, Frustrated, Excited, Grateful, Surprised), and summary (a concise 1-sentence explanation of why that sentiment/emotion was chosen). Do not return markdown. Return only raw JSON.'
        },
        {
          role: 'user',
          content: `Analyze the sentiment of this text:\n\n"${text}"`
        }
      ],
      response_format: { type: 'json_object' },
      temperature: 0.1,
    });

    const responseText = response.choices[0]?.message?.content;
    if (!responseText) {
      throw new Error('Received empty response from Groq API.');
    }

    const parsed = JSON.parse(responseText.trim());
    return {
      sentiment: sanitizeSentiment(parsed.sentiment),
      confidence: typeof parsed.confidence === 'number' ? parsed.confidence : 75,
      emotion: parsed.emotion || 'Neutral',
      summary: parsed.summary || 'Summary generated by Groq.',
    };
  } catch (error: any) {
    logger.error('[GroqService] Error calling Groq API:', error.message);
    return getMockResult(text, 'Groq');
  }
};
